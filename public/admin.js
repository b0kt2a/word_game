/* ==========================================
   Socket.IO 연결
========================================== */

const socket = io();


/* ==========================================
   DOM 요소를 쉽게 가져오기 위한 함수

   $("key")
   ↓
   document.getElementById("key")
========================================== */

const $ = id => document.getElementById(id);


/* ==========================================
   운영자 키

   같은 탭에서 새로고침해도
   다시 입력하지 않도록 sessionStorage에 저장

   브라우저 탭을 완전히 닫으면 사라짐
========================================== */

let key =
    sessionStorage.getItem("bangpingAdminKey") || "";



/* ==========================================
   저장된 운영자 키가 있으면 자동 로그인
========================================== */

if (key) {

    $("key").value = key;

    login();

}



/* ==========================================
   운영자 로그인 버튼
========================================== */

$("loginBtn").onclick = login;



/* ==========================================
   운영자 로그인 요청

   입력한 운영자 키를 서버로 전송

   실제 비밀번호 확인은
   server.js의 ADMIN_KEY와 비교해서 처리
========================================== */

function login() {

    key = $("key").value;

    socket.emit(
        "admin:join",
        {
            key
        }
    );

}



/* ==========================================
   운영자 오류 메시지

   예:
   운영자 키가 맞지 않습니다.
   CSV에서 문제를 찾지 못했습니다.
========================================== */

socket.on(
    "admin:error",
    message => {

        $("notice").textContent = message;

    }
);



/* ==========================================
   운영자 안내 메시지

   예:
   20개 문제를 불러왔습니다.
========================================== */

socket.on(
    "admin:notice",
    message => {

        $("notice").textContent = message;

    }
);



/* ==========================================
   서버에서 운영자 상태 수신

   참가자 입장
   정답 발생
   문제 시작
   문제 이동
   정답 공개

   등 게임 상태가 바뀔 때마다 실행됨
========================================== */

socket.on(
    "admin:state",
    state => {

        /* 운영자 키를 현재 탭에 저장 */
        sessionStorage.setItem(
            "bangping0912",
            key
        );


        /* 로그인 화면 숨김 */
        $("login").classList.add("hidden");


        /* 운영자 콘솔 표시 */
        $("console").classList.remove("hidden");


        /* 화면 업데이트 */
        render(state);

    }
);



