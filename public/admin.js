/* ==========================================
   운영자 화면 전체 업데이트

   서버에서 받은 상태값을 이용해서
   화면 내용을 다시 그림
========================================== */

function render(state) {


    /* ======================================
       1. 현재 게임 상태

       대기중..
       게임 진행중..
       정답 공개

       현재는 서버 상태값 그대로 표시
    ====================================== */

    $("phase").textContent =
        state.phase;



    /* ======================================
       2. 현재 문제 번호 + 문제 방식

       예:
       문제 3 / 20 · 자모

       문제가 없으면:
       문제 없음
    ====================================== */

    $("question").textContent =
        state.questionNumber > 0
            ? `문제 ${state.questionNumber} / ${state.totalQuestions} · ${state.mode}`
            : "문제 없음";



    /* ======================================
       3. 현재 문제 정답

       운영자 화면에서는 항상 확인 가능
    ====================================== */

    $("answer").textContent =
        state.answer || "";



    /* ======================================
       4. 현재 문제 전체 힌트

       힌트1
       힌트2
       힌트3
       ...

       운영자는 참가자가 사용하지 않았어도
       모든 힌트를 볼 수 있음
    ====================================== */

    $("hints").innerHTML =
        (state.hints || [])

            .map(
                (hint, index) =>
                    `힌트 ${index + 1}: ${esc(hint)}`
            )

            .join("<br>");



    /* ======================================
       5. 참가자 수 / 현재 정답자 수

       예:
       참가자 25명 · 정답자 8명
    ====================================== */

    $("counts").textContent =
        `참가자 ${state.participantCount}명 · ` +
        `정답자 ${state.winnerCount}명`;



    /* ======================================
       6. 실시간 정답 순위

       예:
       1위 복티
       2회 · 💡0 · 0분 24초
    ====================================== */

    $("winners").innerHTML =

        (state.winners || [])

            .map(
                winner => `

                    <div class="winner">

                        <!-- 순위 -->
                        <b>
                            ${winner.rank}위
                        </b>


                        <!-- 닉네임 -->
                        <b>
                            ${esc(winner.nickname)}
                        </b>


                        <!--
                            시도 횟수
                            힌트 사용 수
                            정답 시간
                        -->
                        <span>
                            ${winner.attempts}회
                            · 💡${winner.hintsUsed}
                            · ${time(winner.elapsedMs)}
                        </span>

                    </div>

                `
            )

            .join("")

        ||

        "아직 정답자가 없습니다.";



    /* ======================================
       7. 현재 누적 기록 개수

       참가자 × 문제 기록 수

       예:
       현재 누적 120개 기록 저장됨
    ====================================== */

    $("records").textContent =
        `현재 누적 ${state.records?.length || 0}개 기록 저장됨`;

}



/* ==========================================
   시간 표시 함수

   서버에서는 시간을 밀리초(ms)로 저장

   예:
   190000ms
   ↓
   3분 10초
========================================== */

function time(ms) {

    /* 시간이 없는 경우 */
    if (ms == null) {
        return "";
    }


    /* 밀리초 → 초 */
    const seconds =
        Math.floor(ms / 1000);


    /* 분 */
    const minutes =
        Math.floor(seconds / 60);


    /* 남은 초 */
    const remainSeconds =
        seconds % 60;


    return (
        `${minutes}분 ` +
        `${String(remainSeconds).padStart(2, "0")}초`
    );

}



/* ==========================================
   HTML 특수문자 처리

   닉네임이나 힌트 안에
   < > & " ' 같은 문자가 들어와도

   HTML 코드로 실행되지 않게 안전하게 변환
========================================== */

function esc(value) {

    return String(value).replace(

        /[&<>"']/g,

        char => ({

            "&": "&amp;",
            "<": "&lt;",
            ">": "&gt;",
            '"': "&quot;",
            "'": "&#39;"

        }[char])

    );

}