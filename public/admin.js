/* ==========================================
   문제 CSV 적용 버튼
========================================== */

$("upload").onclick = () => {

    /* 선택한 CSV 파일 */
    const file = $("csv").files[0];


    /* 파일이 선택되지 않았으면 종료 */
    if (!file) {
        return;
    }


    /* 파일 읽기 */
    const reader =
        new FileReader();


    /* 파일을 모두 읽었을 때 */
    reader.onload = () => {

        /*
            CSV 내용을 서버로 전송

            server.js에서
            정답 / 분류코드 / 힌트 등을 읽어서
            문제 목록으로 변경
        */
        socket.emit(
            "admin:csv",
            {
                csv: reader.result
            }
        );

    };


    /* UTF-8로 CSV 파일 읽기 */
    reader.readAsText(
        file,
        "utf-8"
    );

};



